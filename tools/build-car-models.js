/*
 * Builds src/car-models.js: the car models of Divar's own catalog (public/divar-models.json),
 * one name per model, for naming the model of every ad (Divar, Bama, Hamrah Mechanic, Khodro45).
 *
 * Divar's catalog is uneven: for Peugeot or Samand its second level is real models (206، پارس،
 * سورن، X7), for Shahin, Saina, Quick or Rana it is trims (G CVT، GL، GX، TU5). So trim words are
 * peeled off the end of each name: «سمند LX» → «سمند», «شاهین G CVT» → «شاهین», «سایپا اطلس E Plus
 * اتوماتیک» → «سایپا اطلس», while «سمند سورن», «تیبا 2 (هاچبک)», «پراید 131» stay models.
 *
 * Run again when divar-models.json is refreshed:  node tools/build-car-models.js
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const P = require('../src/parser');

const ROOT = path.join(__dirname, '..');
const cat = JSON.parse(fs.readFileSync(path.join(ROOT, 'public', 'divar-models.json'), 'utf8'));

// words that name a trim, a gearbox, a fuel or an engine, not a model
const TRIM_LATIN = /^(g|gl|gx|gxl|gxr|gxh|gli|glx|gs|s|sx|se|ex|e|el|elx|l|lx|r|rs|sd|cvt|at|mt|plus|tu3|tu5|tu5p|xu7|xu7p|ef7|ef7p|v\d+|\d+\.\d+|turbo|hybrid|cng)$/i;
const TRIM_FA = /^(اتوماتیک|اتومات|دنده|ای|دستی|پلاس|معمولی|بنزینی|دوگانه|سوز|توربو|لیتر|پانوراما|تیپ|ساده|آپشنال|فول|اسپرت)$/;

function modelName(fa) {
  // «2 لیتر» / «1.5 لیتر»: the engine size goes with its number
  const words = P.normalizeText(fa).replace(/\d+(\.\d+)?\s*لیتر/g, ' ').split(' ').filter(Boolean);
  while (words.length > 1 && (TRIM_LATIN.test(words[words.length - 1]) || TRIM_FA.test(words[words.length - 1]))) words.pop();
  return words.join(' ');
}

const names = new Set();
for (const b of cat.brands || []) {
  const brand = P.normalizeText(b.fa);
  const models = (b.models || []).map((m) => modelName(m.fa));
  // the make's name alone is a model only when the catalog lists it so (no models, or trims of it:
  // «شاهین»، «سمند LX» → «سمند»); a make with its own models (تویوتا کرولا …) is not, so an ad's
  // «تویوتا راوفور» that the catalog does not spell keeps its own two words
  if (!models.length || models.includes(brand)) names.add(brand);
  for (const m of models) names.add(m);
}
const list = Array.from(names).filter(Boolean).sort((a, b) => a.localeCompare(b, 'fa'));

const out = `/*
 * Car models of Divar's catalog, one name per model (generated by tools/build-car-models.js from
 * public/divar-models.json — do not edit by hand). Used by parser.js to name the model of an ad.
 */
(function (root) {
  'use strict';
  const MODELS = ${JSON.stringify(list)};
  root.NojaCarModels = MODELS;
  if (typeof module !== 'undefined' && module.exports) module.exports = MODELS;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
fs.writeFileSync(path.join(ROOT, 'src', 'car-models.js'), out);
console.log(`src/car-models.js: ${list.length} models`);
